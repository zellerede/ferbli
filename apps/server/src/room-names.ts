function pickPair(): string {
  const a = ADJECTIVES[randomInt(ADJECTIVES.length)]!;
  const b = NOUNS[randomInt(NOUNS.length)]!;
  return `${a}-${b}`;
}

/** One random `adjective_noun` slug (lowercase). Caller retries if already taken. */
export function randomRoomSlug(): string {
  return pickPair();
}
